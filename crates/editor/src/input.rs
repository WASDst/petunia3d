use petunia_config::keybinds::winit_keys::KeyCode;

pub(crate) fn key_code_from_slint(text: &str) -> Option<KeyCode> {
    if text == " " {
        return Some(KeyCode::Space);
    }
    let normalized = text.trim();
    if normalized.len() == 1 {
        let character = normalized.chars().next()?.to_ascii_uppercase();
        return match character {
            'A' => Some(KeyCode::KeyA),
            'B' => Some(KeyCode::KeyB),
            'C' => Some(KeyCode::KeyC),
            'D' => Some(KeyCode::KeyD),
            'E' => Some(KeyCode::KeyE),
            'F' => Some(KeyCode::KeyF),
            'G' => Some(KeyCode::KeyG),
            'H' => Some(KeyCode::KeyH),
            'I' => Some(KeyCode::KeyI),
            'J' => Some(KeyCode::KeyJ),
            'K' => Some(KeyCode::KeyK),
            'L' => Some(KeyCode::KeyL),
            'M' => Some(KeyCode::KeyM),
            'N' => Some(KeyCode::KeyN),
            'O' => Some(KeyCode::KeyO),
            'P' => Some(KeyCode::KeyP),
            'Q' => Some(KeyCode::KeyQ),
            'R' => Some(KeyCode::KeyR),
            'S' => Some(KeyCode::KeyS),
            'T' => Some(KeyCode::KeyT),
            'U' => Some(KeyCode::KeyU),
            'V' => Some(KeyCode::KeyV),
            'W' => Some(KeyCode::KeyW),
            'X' => Some(KeyCode::KeyX),
            'Y' => Some(KeyCode::KeyY),
            'Z' => Some(KeyCode::KeyZ),
            '0' => Some(KeyCode::Digit0),
            '1' => Some(KeyCode::Digit1),
            '2' => Some(KeyCode::Digit2),
            '3' => Some(KeyCode::Digit3),
            '4' => Some(KeyCode::Digit4),
            '5' => Some(KeyCode::Digit5),
            '6' => Some(KeyCode::Digit6),
            '7' => Some(KeyCode::Digit7),
            '8' => Some(KeyCode::Digit8),
            '9' => Some(KeyCode::Digit9),
            '[' => Some(KeyCode::BracketLeft),
            ']' => Some(KeyCode::BracketRight),
            '/' => Some(KeyCode::Slash),
            '.' => Some(KeyCode::Period),
            ',' => Some(KeyCode::Comma),
            '-' => Some(KeyCode::Minus),
            '=' => Some(KeyCode::Equal),
            '`' => Some(KeyCode::Backquote),
            ';' => Some(KeyCode::Semicolon),
            '\'' => Some(KeyCode::Quote),
            '\\' => Some(KeyCode::Backslash),
            _ => None,
        };
    }
    match normalized {
        "Delete" => Some(KeyCode::Delete),
        "Backspace" => Some(KeyCode::Backspace),
        "Home" => Some(KeyCode::Home),
        "End" => Some(KeyCode::End),
        "Enter" => Some(KeyCode::Enter),
        "Escape" => Some(KeyCode::Escape),
        "Tab" => Some(KeyCode::Tab),
        "Space" => Some(KeyCode::Space),
        "Up" => Some(KeyCode::Up),
        "Down" => Some(KeyCode::Down),
        "Left" => Some(KeyCode::Left),
        "Right" => Some(KeyCode::Right),
        "PageUp" => Some(KeyCode::PageUp),
        "PageDown" => Some(KeyCode::PageDown),
        "Insert" => Some(KeyCode::Insert),
        "F1" => Some(KeyCode::F1),
        "F2" => Some(KeyCode::F2),
        "F3" => Some(KeyCode::F3),
        "F4" => Some(KeyCode::F4),
        "F5" => Some(KeyCode::F5),
        "F6" => Some(KeyCode::F6),
        "F7" => Some(KeyCode::F7),
        "F8" => Some(KeyCode::F8),
        "F9" => Some(KeyCode::F9),
        "F10" => Some(KeyCode::F10),
        "F11" => Some(KeyCode::F11),
        "F12" => Some(KeyCode::F12),
        "Numpad0" | "Numpad 0" | "KP_0" | "Keypad0" | "NumPad0" => Some(KeyCode::Numpad0),
        "Numpad1" | "Numpad 1" | "KP_1" | "Keypad1" | "NumPad1" => Some(KeyCode::Numpad1),
        "Numpad2" | "Numpad 2" | "KP_2" | "Keypad2" | "NumPad2" => Some(KeyCode::Numpad2),
        "Numpad3" | "Numpad 3" | "KP_3" | "Keypad3" | "NumPad3" => Some(KeyCode::Numpad3),
        "Numpad4" | "Numpad 4" | "KP_4" | "Keypad4" | "NumPad4" => Some(KeyCode::Numpad4),
        "Numpad5" | "Numpad 5" | "KP_5" | "Keypad5" | "NumPad5" => Some(KeyCode::Numpad5),
        "Numpad6" | "Numpad 6" | "KP_6" | "Keypad6" | "NumPad6" => Some(KeyCode::Numpad6),
        "Numpad7" | "Numpad 7" | "KP_7" | "Keypad7" | "NumPad7" => Some(KeyCode::Numpad7),
        "Numpad8" | "Numpad 8" | "KP_8" | "Keypad8" | "NumPad8" => Some(KeyCode::Numpad8),
        "Numpad9" | "Numpad 9" | "KP_9" | "Keypad9" | "NumPad9" => Some(KeyCode::Numpad9),
        "Numpad." | "Numpad ." | "KP_Decimal" | "NumpadPeriod" | "NumpadDecimal" => {
            Some(KeyCode::NumpadPeriod)
        }
        "Numpad/" | "Numpad /" | "KP_Divide" | "NumpadDivide" => Some(KeyCode::NumpadDivide),
        "Numpad*" | "Numpad *" | "KP_Multiply" | "NumpadMultiply" => Some(KeyCode::NumpadMultiply),
        "Numpad-" | "Numpad -" | "KP_Subtract" | "NumpadSubtract" => Some(KeyCode::NumpadMinus),
        "Numpad+" | "Numpad +" | "KP_Add" | "NumpadAdd" => Some(KeyCode::NumpadPlus),
        _ => None,
    }
}
