def main():
    catalog = json.loads(CATALOG.read_text(encoding="utf-8"))
    added = 0
    for source, english in PT_TO_EN.items():
        entry = catalog.setdefault(source, {})
        if "pt-BR" not in entry:
            entry["pt-BR"] = source
        if "en" not in entry:
            entry["en"] = english
        added += 1
    for source, portuguese in EN_TO_PT.items():
        entry = catalog.setdefault(source, {})
        if "pt-BR" not in entry:
            entry["pt-BR"] = portuguese
        if "en" not in entry:
            entry["en"] = source
        added += 1
    CATALOG.write_text(json.dumps(catalog, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"{added} entradas verificadas; catálogo com {len(catalog)} chaves")


if __name__ == "__main__":
    main()
